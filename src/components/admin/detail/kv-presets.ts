/* ============================================================
   영양·스펙에서 자주 쓰는 항목 이름 모음 + 저장 한도.

   왜 프리셋인가:
   식품 상세는 항목 이름이 거의 정해져 있다. 운영 중인 27개 상품에서
   실제로 반복되는 이름을 모았다(우동인데곤약은 스펙 22개 + 영양 12개 = 34행이다).
   그런데 옛 편집기에는 '항목 추가' 버튼 하나뿐이라, 34행을 만들려면
   빈 행을 34번 만들고 항목 이름을 34번 손으로 타이핑해야 했다.
   이름을 눌러 넣게 하면 오타도 사라진다 — 같은 뜻인데 '보관방법'과 '보관 방법'이
   섞이면 고객 화면 표에 두 줄로 따로 뜬다.
   ============================================================ */

